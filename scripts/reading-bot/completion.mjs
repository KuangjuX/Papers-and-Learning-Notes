import { readFile, readdir } from 'node:fs/promises';
import { join, posix } from 'node:path';

// Only the authenticated triggering request may opt into closing. Quoted
// discussion, examples, model summaries and unrelated Issue numbers cannot.
export function completionDirective(text, issue) {
  let fence;
  const prose = text.split(/\r?\n/).filter(line => {
    const delimiter = line.match(/^\s*(`{3,}|~{3,})(.*)$/);
    if (fence) {
      if (delimiter && delimiter[1][0] === fence[0] && delimiter[1].length >= fence.length && !delimiter[2].trim()) fence = undefined;
      return false;
    }
    if (delimiter) { fence = delimiter[1]; return false; }
    return !fence && !/^\s*>/.test(line);
  }).join('\n').replace(/`[^`]*`|“[^”]*”|「[^」]*」|‘[^’]*’|"[^"]*"/g, '');
  if (/(?:不要|不需要|无需|别|不应|不想|暂不)[^。；;，,\n]{0,16}(?:关闭|close)|(?:issue|问题).{0,12}(?:保持打开|保留打开)|保持\s*(?:issue\s*)?打开|do not close|don't close|keep.{0,12}open/i.test(prose)) return false;
  if (/(?:尚未|还没|没有|未)读完|(?:不要|不需要|无需|别|不应|不想|暂不|不)[^。；;，,\n]{0,12}(?:已读|读完)|not.{0,8}(?:finished|read)/i.test(prose)) return false;
  for (const sentence of prose.match(/[^。！？!?\n；;]+[。！？!?]?/g) ?? []) {
    if (/[?？]|[吗呢]\s*[。！!]?\s*$/.test(sentence)) continue;
    if (/(?:是否|能否|是不是|如何|怎么|如果|假设|例如|比如)|\b(?:how|whether|example|if)\b/i.test(sentence)) continue;
    const match = sentence.match(/(?:PR|pull request)\s*(?:#\d+\s*)?(?:成功\s*)?合并(?:完成)?(?:之)?后[，,\s]*(?:请|再|自动|就|帮我|将|把|这个|当前|该|本|的|\s)*(?:关闭\s*(?:这个|当前|该|本)?\s*issue|(?:这个|当前|该|本)?\s*issue\s*关闭)\s*(?:#\s*)?(\d+)?/i)
      ?? sentence.match(/after\s+(?:the\s+)?(?:PR|pull request)\s+(?:is\s+)?merged[,\s]+(?:please\s+)?(?:automatically\s+)?close\s+(?:this\s+|the\s+)?issue\s*(?:#\s*)?(\d+)?/i);
    if (match && (!match[1] || Number(match[1]) === issue)) return true;
  }
  return null;
}

export const completionMarker = issue => `<!-- reading-bot-completion:issue-${issue} -->`;
const partial = '本次是阶段性整理，PR 留待审阅，不代表论文阅读完成。';
export function completionBlock(issue, complete) {
  return `<!-- reading-bot-completion:start -->\n${complete ? `${completionMarker(issue)}\nCloses #${issue}\n\n用户明确要求合并后关闭本 Issue；论文条目已按此要求标记为已读，项目笔记不新增论文阅读状态。PR 留待审阅，合并到默认分支后自动关闭 Issue。` : `Refs #${issue}\n\n${partial}`}\n<!-- reading-bot-completion:end -->`;
}

export function updateCompletionBody(body, issue, complete) {
  const block = completionBlock(issue, complete);
  const managed = /<!-- reading-bot-completion:start -->[\s\S]*?<!-- reading-bot-completion:end -->/;
  if (managed.test(body)) return body.replace(managed, () => block);
  // Migrate only the exact paragraph generated by older bot versions.
  const legacy = `Refs #${issue}\n\n${partial}`;
  if (body.includes(legacy)) return body.replace(legacy, () => block);
  return `${body.trimEnd()}\n\n${block}`;
}

export function completionInstructions(job) {
  return job.closeOnMerge
    ? `阅读完成约定：本次已确认“PR 合并后关闭 Issue #${job.issue}”。按用户约定，这同时表示对应论文已读完。必须在所属 Papers 主题 index.md 的该论文行标记 ✅，保留 📝、链接和其他条目；同步 README 阅读清单。项目源码笔记只完成项目任务，不虚构论文条目。发布程序会写入 Closes #${job.issue}，由 GitHub 在合并后自动关闭；不要自行合并或关闭。复核时必须检查已读状态与正文、索引对应。`
    : '本次未授权合并后自动关闭 Issue；继续按用户明确的阅读状态维护，不因生成笔记自动标记已读。';
}

const normalize = text => text.toLowerCase().replace(/\[[^\]]*\]|【[^】]*】/g, '').replace(/^(?:论文阅读|阅读|paper reading)\s*[:：]?\s*/i, '').replace(/[^\p{L}\p{N}]/gu, '');
export async function completionProblems(workspace, issue, files) {
  const indexes = [];
  async function walk(path) {
    let entries;
    try { entries = await readdir(join(workspace, path), { withFileTypes: true }); }
    catch (error) { if (error.code === 'ENOENT') return; throw error; }
    for (const entry of entries) {
      const child = `${path}/${entry.name}`;
      if (entry.isDirectory() && !entry.name.startsWith('.')) await walk(child);
      else if (entry.isFile() && entry.name === 'index.md') indexes.push(child);
    }
  }
  await walk('Papers');
  const rows = [];
  for (const path of indexes) {
    for (const line of (await readFile(join(workspace, path), 'utf8')).split('\n')) {
      if (!/^\|\s*(?:✅|⬜)/u.test(line)) continue;
      const title = line.match(/\*\*([^*]+)\*\*/)?.[1];
      if (!title) continue;
      const links = [...line.matchAll(/\]\(([^)]+\.md)(?:#[^)]*)?\)/g)].map(m => posix.normalize(posix.join(posix.dirname(path), m[1])));
      rows.push({ path, line, title, links });
    }
  }
  const title = normalize(issue.title);
  let matched = rows.filter(row => normalize(row.title) === title || normalize(row.title.split(/[:：]/)[0]) === title);
  if (!matched.length) {
    const papers = files.filter(f => !f.deleted && /^Papers\/.+\.md$/.test(f.path) && !f.path.endsWith('/index.md'));
    if (papers.length === 1) matched = rows.filter(row => row.links.includes(papers[0].path));
  }
  if (!matched.length && (/^\s*(?:\[代码阅读\]|【代码阅读】)/.test(issue.title)
    || (!/论文/.test(issue.title) && !files.some(f => f.path.startsWith('Papers/')) && files.some(f => f.path.startsWith('Projects/'))))) return [];
  if (!matched.length) return ['无法唯一定位当前论文的阅读清单条目；请在所属 Papers 主题 index.md 建立对应主笔记链接并标记为已读 ✅。'];
  return matched.filter(row => !/^\|\s*✅/u.test(row.line)).map(row => `${row.path}：${row.title} 尚未标记为已读 ✅，不能发布合并后关闭 Issue 的 PR。`);
}
